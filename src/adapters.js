export function toGenericConfig(routeExport) {
  const rules = routeExport.routing_rules ?? [];
  return {
    schema_version: 'routebench.generic-router.v1',
    generated_at: routeExport.generated_at,
    comment: 'Generic router config draft generated by RouteBench. Adapt field names for your specific router.',
    endpoint: routeExport.endpoint ?? '',
    default_model: routeExport.primary_model ?? null,
    fallback_chain: routeExport.fallback_models ?? [],
    models: rules.map((rule, index) => ({
      id: rule.model,
      priority: rule.priority,
      route_score: rule.route_score,
      overall_score: rule.overall_score,
      avg_latency_ms: rule.avg_latency_ms,
      error_rate: rule.error_rate,
      recommended_use: index === 0 ? 'primary' : 'fallback',
      reason: rule.reason,
    })),
    routing_hint: selectRoutingHint(rules),
  };
}

function selectRoutingHint(rules) {
  if (rules.length === 0) return 'no models';
  const primary = rules[0];
  if (primary.error_rate === 0 && primary.avg_latency_ms <= 2000) return 'latency-optimized';
  if (primary.error_rate === 0) return 'quality-first with fallback';
  return 'best-effort with fallback';
}

function yamlStr(value) {
  if (typeof value !== 'string') return String(value);
  if (/[\s:#{}[\],&*?|<>=!%@`]/.test(value)) return `"${value.replace(/"/g, '\\"')}"`;
  return value;
}

export function toLiteLLMConfig(routeExport, { apiKeyEnv = 'ROUTEBENCH_API_KEY' } = {}) {
  const rules = routeExport.routing_rules ?? [];
  const endpoint = routeExport.endpoint ?? '';
  const lines = [];

  lines.push('# Generated by RouteBench');
  lines.push('# Source: routebench.routing.v1 → LiteLLM router config');
  lines.push('# Docs: https://docs.litellm.ai/docs/routing');
  lines.push('# Adapt model_name values and router_settings for your deployment.');
  lines.push('');
  lines.push('model_list:');

  for (const rule of rules) {
    const tag = rule.priority === 1 ? 'routebench-primary' : `routebench-fallback-${rule.priority - 1}`;
    lines.push(`  - model_name: ${yamlStr(tag)}`);
    lines.push('    litellm_params:');
    lines.push(`      model: openai/${yamlStr(rule.model)}`);
    lines.push(`      api_base: ${yamlStr(endpoint)}`);
    lines.push(`      api_key: os.environ/${apiKeyEnv}`);
    lines.push('    model_info:');
    lines.push(`      # route_score: ${rule.route_score}`);
    lines.push(`      # overall_score: ${rule.overall_score}`);
    lines.push(`      # avg_latency_ms: ${rule.avg_latency_ms}`);
    lines.push(`      # error_rate: ${rule.error_rate}`);
    lines.push(`      # reason: ${rule.reason}`);
    lines.push('');
  }

  const primaryTag = 'routebench-primary';
  const fallbackTags = rules.slice(1).map((r, i) => `routebench-fallback-${i + 1}`);

  lines.push('router_settings:');
  lines.push('  routing_strategy: latency-based-routing');
  if (fallbackTags.length > 0) {
    lines.push('  fallbacks:');
    lines.push(`    - ${primaryTag}: [${fallbackTags.join(', ')}]`);
  }
  lines.push('  num_retries: 2');
  lines.push('  timeout: 30');
  lines.push('');

  return lines.join('\n');
}
